"""Validated public request and response contracts."""

from enum import Enum
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator


class Relation(str, Enum):
    """The only relation families allowed in predictive evidence."""

    BINDS = "BINDS"
    ASSOCIATES = "ASSOCIATES"
    INTERACTS = "INTERACTS"
    PARTICIPATES = "PARTICIPATES"


class ExtensibleResponse(BaseModel):
    """Allow documented scientific metadata while validating stable fields."""

    model_config = ConfigDict(extra="allow")


class Entity(ExtensibleResponse):
    """Namespace-qualified entity identity."""

    id: str
    name: str


class Features(ExtensibleResponse):
    """Counts of supported, typed evidence paths."""

    direct: float = 0
    interaction: float = 0
    pathway: float = 0


class Candidate(Entity):
    """A research candidate, never a clinical recommendation."""

    rank: int = Field(ge=1)
    score: float
    baseline_rank: int | None = None
    rank_delta: int | None = None
    known_treatment: bool = False
    features: Features
    evidence_count: int = Field(ge=0)


class RankingResponse(ExtensibleResponse):
    """Paginated candidate ranking and its interpretation."""

    disease: Entity
    candidates: list[Candidate]
    total: int = Field(ge=0)
    excluded: list[str]


class EvidenceResponse(ExtensibleResponse):
    """Bounded displayed paths with unbounded-count truncation disclosure."""

    disease: Entity
    compound: Entity
    nodes: list[dict[str, Any]]
    edges: list[dict[str, Any]]
    paths: list[dict[str, Any]]
    counts: Features
    total_paths: int = Field(ge=0)
    truncated: bool
    excluded: list[str]


class ChallengeRequest(BaseModel):
    """Recompute features after removing specific evidence families."""

    model_config = ConfigDict(extra="forbid")
    disease_id: str = Field(min_length=1, max_length=180)
    exclude: list[Relation] = Field(min_length=1, max_length=4)
    limit: int = Field(default=12, ge=1, le=50)

    @field_validator("exclude")
    @classmethod
    def deduplicate(cls, value: list[Relation]) -> list[Relation]:
        """Canonicalize the exclusion set for cache keys and exports."""
        return sorted(set(value), key=lambda relation: relation.value)


class ChallengeResponse(ExtensibleResponse):
    """Before/after rankings generated by one fixed fitted model."""

    disease: Entity
    excluded: list[str]
    before: list[Candidate]
    after: list[Candidate]
    changes: list[dict[str, Any]]
    explanation: str


class AgentRequest(BaseModel):
    """Bounded natural-language investigation request."""

    model_config = ConfigDict(extra="forbid")
    question: str = Field(min_length=3, max_length=2000)
    disease_id: str | None = Field(default=None, max_length=180)
    exclude: list[Relation] = Field(default_factory=list, max_length=4)


class AgentResponse(ExtensibleResponse):
    """Transparent agent execution including refusal and clarification."""

    status: Literal["complete", "rejected", "clarification"]
    answer: str
    mode: Literal["llm", "deterministic"]
    candidates: list[dict[str, Any]] = Field(default_factory=list)
    citations: list[dict[str, Any]] = Field(default_factory=list)
    trace: list[dict[str, str]] = Field(default_factory=list)
    suggestions: list[dict[str, str] | str] = Field(default_factory=list)
    disclaimer: str


class HealthResponse(BaseModel):
    """Runtime state, without implying disconnected dependencies are healthy."""

    status: str
    graph_backend: str
    dataset_ready: bool
    agent_mode: str
    version: str


class DiseaseResponse(BaseModel):
    """Paginated disease dictionary."""

    items: list[Entity]
    total: int


def parse_exclusions(value: str) -> tuple[str, ...]:
    """Validate and canonicalize comma-separated relation types."""
    if not value:
        return ()
    return tuple(sorted({Relation(part.strip().upper()).value for part in value.split(",")}))
