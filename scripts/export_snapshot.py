"""Publish complete, explicitly recorded research cases for the browser edition.

Every ranking, evidence path, similarity and ablation is generated by the same
GraphEngine used by the live API. This exports data, not simulated LLM answers.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import itertools
import json
from pathlib import Path
import re
import time

from app.graph_engine import DISCLAIMER, FAMILIES, GraphEngine
from scripts.prepare_data import write_json

DEFAULT_DISEASES = (
    "Disease::DOID:10652",  # Alzheimer's disease
    "Disease::DOID:2377",  # multiple sclerosis
    "Disease::DOID:2841",  # asthma
    "Disease::DOID:1459",  # hypothyroidism
    "Disease::DOID:9352",  # type 2 diabetes mellitus
    "Disease::DOID:7148",  # rheumatoid arthritis
)


def exclusion_combinations() -> list[tuple[str, ...]]:
    """Generate all sixteen relationship-family choices in a canonical order."""
    families = sorted(FAMILIES)
    return [
        combination
        for count in range(len(families) + 1)
        for combination in itertools.combinations(families, count)
    ]


def case_filename(disease: dict) -> str:
    """Create a readable, filesystem-safe filename with an unambiguous disease ID."""
    slug = re.sub(r"[^a-z0-9]+", "-", disease["name"].casefold()).strip("-")
    identifier = re.sub(r"[^a-z0-9]+", "-", disease["id"].casefold()).strip("-")
    return f"cases/{slug}-{identifier}.json"


def build_case(engine: GraphEngine, disease_id: str, top_k: int = 12) -> dict:
    """Materialize every supported interaction for one published disease case."""
    rankings = {}
    challenges = {}
    compounds = set()
    combinations = exclusion_combinations()
    for excluded in combinations:
        key = ",".join(excluded)
        result = engine.rankings(disease_id, exclude=excluded, limit=top_k)
        rankings[key] = result
        compounds.update(candidate["id"] for candidate in result["candidates"])
        challenges[key] = engine.challenge(disease_id, exclude=excluded, limit=top_k)
    # The union allows an already selected compound to remain inspectable even
    # when evidence removal moves it outside the currently displayed top-k.
    evidence = {
        compound_id: {
            ",".join(excluded): engine.evidence(disease_id, compound_id, exclude=excluded, limit=12)
            for excluded in combinations
        }
        for compound_id in sorted(compounds)
    }
    return {
        "disease": rankings[""]["disease"],
        "rankings": rankings,
        "evidence": evidence,
        "challenges": challenges,
        "algorithms": engine.algorithms(disease_id, limit=10),
        "similarities": {
            identifier: engine.similar(identifier, limit=10) for identifier in sorted(compounds)
        },
        "coverage": {
            "exclusion_configurations": len(combinations),
            "top_k": top_k,
            "distinct_compounds": len(compounds),
            "evidence_path_limit": 12,
            "selection_policy": (
                "Exact ranked top-k for each configuration; evidence for their union under "
                "all configurations. Empty configurations are explicit."
            ),
        },
    }


def validate_case(case: dict) -> None:
    """Fail export if any displayed ranking, evidence configuration or endpoint is missing."""
    expected = {",".join(excluded) for excluded in exclusion_combinations()}
    if set(case["rankings"]) != expected or set(case["challenges"]) != expected:
        raise ValueError("A published case is missing an evidence configuration")
    for key, ranking in case["rankings"].items():
        for candidate in ranking["candidates"]:
            if candidate["id"] not in case["evidence"]:
                raise ValueError("A displayed candidate is missing evidence")
            evidence = case["evidence"][candidate["id"]].get(key)
            if evidence is None:
                raise ValueError("A displayed candidate is missing scenario evidence")
            if evidence["counts"] != candidate["features"]:
                raise ValueError("Displayed path counts do not match ranking features")
            if evidence["total_paths"] != candidate["evidence_count"]:
                raise ValueError("Displayed total evidence count is inconsistent")
            if set(evidence["excluded"]) != set(ranking["excluded"]):
                raise ValueError("Evidence and ranking refer to different configurations")
            if any(edge["type"] in ranking["excluded"] for edge in evidence["edges"]):
                raise ValueError("A removed family appears in a published explanation")
    for variants in case["evidence"].values():
        if set(variants) != expected:
            raise ValueError("Selected candidates cannot be inspected in all configurations")


def export_snapshot(
    engine: GraphEngine, output: Path, disease_ids=DEFAULT_DISEASES, top_k: int = 12
) -> dict:
    """Write verified cases and a manifest with their exact checksums."""
    started = time.perf_counter()
    if top_k < 1 or top_k > 100:
        raise ValueError("Snapshot top_k must be between 1 and 100")
    disease_ids = tuple(dict.fromkeys(disease_ids))
    if not disease_ids:
        raise ValueError("At least one disease is required")
    output = Path(output)
    (output / "cases").mkdir(parents=True, exist_ok=True)
    cases, diseases, files = {}, [], []
    for disease_id in disease_ids:
        case = build_case(engine, disease_id, top_k)
        validate_case(case)
        filename = case_filename(case["disease"])
        path = output / filename
        write_json(path, case)
        content = path.read_bytes()
        cases[disease_id] = {"file": filename, "coverage": case["coverage"]}
        diseases.append(case["disease"])
        files.append(
            {"path": filename, "bytes": len(content), "sha256": hashlib.sha256(content).hexdigest()}
        )
        print(f"Exported {case['disease']['name']}: {len(content):,} bytes", flush=True)
    manifest = {
        "mode": "snapshot",
        "schema_version": "1.0",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "generated_by": "python -m scripts.export_snapshot",
        "default_disease_id": disease_ids[0],
        "diseases": diseases,
        "cases": cases,
        "stats": engine.stats(),
        "provenance": engine.provenance(),
        "evaluation": engine.evaluation(),
        "health": {
            "status": "ok",
            "graph_backend": "published research snapshot",
            "agent_mode": "deterministic",
            "dataset_ready": True,
            "version": "1.0.0",
        },
        "dataset_sha256": engine.manifest.get("dataset_sha256"),
        "model_sha256": engine.model.get("model_sha256"),
        "files": files,
        "file_count": len(files),
        "case_count": len(cases),
        "total_case_bytes": sum(item["bytes"] for item in files),
        "exclusion_configurations_per_case": 16,
        "full_application_disease_count": len(engine.entities["Disease"]),
        "scope": (
            "Published, recorded results for six research cases. All sixteen family "
            "exclusion configurations are included. The full Docker application queries "
            "Neo4j and can investigate every disease in the dataset."
            if len(cases) == 6
            else "Published, recorded research cases with all sixteen evidence configurations."
        ),
        "agent_disclosure": (
            "The hosted snapshot formats retrieved records deterministically. No live LLM "
            "or live database executes in this static edition. The full application exposes "
            "the LangGraph workflow and configured LLM provider."
        ),
        "disclaimer": DISCLAIMER,
        "runtime_seconds": round(time.perf_counter() - started, 3),
    }
    write_json(output / "manifest.json", manifest)
    return manifest


def main() -> None:
    """Generate the browser's data directory from executed graph/model artifacts."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=Path("data/processed"))
    parser.add_argument("--output", type=Path, default=Path("frontend/data"))
    parser.add_argument("--disease", action="append", help="Disease ID; may be repeated")
    parser.add_argument("--top-k", type=int, default=12)
    args = parser.parse_args()
    manifest = export_snapshot(
        GraphEngine(args.data_dir), args.output, args.disease or DEFAULT_DISEASES, args.top_k
    )
    print(
        json.dumps(
            {
                key: manifest[key]
                for key in ("case_count", "file_count", "total_case_bytes", "runtime_seconds")
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
