"""Publish complete, explicitly recorded research cases for the browser edition.

Every ranking, evidence path, similarity and ablation is generated by the same
GraphEngine used by the live API. This exports data, not simulated LLM answers.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import itertools
import json
import math
from pathlib import Path
import re
import tempfile
import time

from app import __version__
from app.audit_schemas import AuditResponse
from app.binding_audit import BindingAuditor, certificate_digest
from app.graph_engine import DISCLAIMER, FAMILIES, FEATURE_NAMES, GraphEngine
from scripts.prepare_data import write_json

DEFAULT_DISEASES = (
    "Disease::DOID:10652",  # Alzheimer's disease
    "Disease::DOID:2377",  # multiple sclerosis
    "Disease::DOID:2841",  # asthma
    "Disease::DOID:1459",  # hypothyroidism
    "Disease::DOID:9352",  # type 2 diabetes mellitus
    "Disease::DOID:7148",  # rheumatoid arthritis
    "Disease::DOID:175",  # vascular cancer; disclosed post-benchmark rival-change example
)
AUDIT_TOP_K = (1, 5, 10)
AUDIT_BUDGETS = (0, 1, 2)


def exclusion_combinations() -> list[tuple[str, ...]]:
    """Generate all sixteen relationship-family choices in a canonical order."""
    families = sorted(FAMILIES)
    return [
        combination
        for count in range(len(families) + 1)
        for combination in itertools.combinations(families, count)
    ]


def case_filename(disease: dict) -> str:
    """Create a readable, filesystem-safe filename with an unambiguous disease ID."""
    slug = re.sub(r"[^a-z0-9]+", "-", disease["name"].casefold()).strip("-")
    identifier = re.sub(r"[^a-z0-9]+", "-", disease["id"].casefold()).strip("-")
    return f"cases/{slug}-{identifier}.json"


def build_case(
    engine: GraphEngine, disease_id: str, top_k: int = 12, auditor: BindingAuditor | None = None
) -> dict:
    """Materialize every supported interaction for one published disease case."""
    rankings = {}
    challenges = {}
    compounds = set()
    combinations = exclusion_combinations()
    for excluded in combinations:
        key = ",".join(excluded)
        result = engine.rankings(disease_id, exclude=excluded, limit=top_k)
        rankings[key] = result
        compounds.update(candidate["id"] for candidate in result["candidates"])
        challenges[key] = engine.challenge(disease_id, exclude=excluded, limit=top_k)
    # The union allows an already selected compound to remain inspectable even
    # when evidence removal moves it outside the currently displayed top-k.
    evidence = {
        compound_id: {
            ",".join(excluded): engine.evidence(disease_id, compound_id, exclude=excluded, limit=12)
            for excluded in combinations
        }
        for compound_id in sorted(compounds)
    }
    assessments = {
        compound_id: {
            ",".join(excluded): engine.assessment(disease_id, compound_id, exclude=excluded)
            for excluded in combinations
        }
        for compound_id in sorted(compounds)
    }
    audits, audit_verifications = _build_audits(
        auditor or BindingAuditor(engine), disease_id, compounds
    )
    return {
        "disease": rankings[""]["disease"],
        "rankings": rankings,
        "evidence": evidence,
        "assessments": assessments,
        "audits": audits,
        "audit_verifications": audit_verifications,
        "audit_demonstration": (
            {
                "compound_id": "Compound::DB01115",
                "top_k": 10,
                "budget": 1,
                "selection": (
                    "Added after the complete 137-disease audit: the sole top-ten query "
                    "where a one-record global withdrawal changes the robustness verdict "
                    "relative to selected-compound-only auditing. This is an illustrative "
                    "case, not a separately selected evaluation cohort."
                ),
            }
            if disease_id == "Disease::DOID:175"
            else None
        ),
        "challenges": challenges,
        "algorithms": engine.algorithms(disease_id, limit=10),
        "similarities": {
            identifier: engine.similar(identifier, limit=10) for identifier in sorted(compounds)
        },
        "coverage": {
            "exclusion_configurations": len(combinations),
            "top_k": top_k,
            "distinct_compounds": len(compounds),
            "evidence_path_limit": 12,
            "assessment_count": len(compounds) * len(combinations),
            "audit_count": len(compounds) * len(AUDIT_TOP_K) * len(AUDIT_BUDGETS),
            "audit_top_k": list(AUDIT_TOP_K),
            "audit_budgets": list(AUDIT_BUDGETS),
            "audit_scope": "Unmodified full graph; all recorded BINDS edges and all compounds",
            "selection_policy": (
                "Exact ranked top-k for each configuration; evidence and exact score "
                "assessments for their union under all configurations. Unsupported and "
                "off-shortlist assessments remain inspectable. Empty configurations are explicit."
            ),
        },
    }


def _build_audits(auditor: BindingAuditor, disease_id: str, compounds: set) -> tuple:
    """Record only claims that pass recomputation and independent witness replay."""
    audits, verifications = {}, {}
    for compound_id in sorted(compounds):
        audits[compound_id], verifications[compound_id] = {}, {}
        for top_k, budget in itertools.product(AUDIT_TOP_K, AUDIT_BUDGETS):
            key = f"{top_k}:{budget}"
            certificate = auditor.audit(disease_id, compound_id, top_k=top_k, budget=budget)
            verification = auditor.verify(certificate)
            if not verification["valid"]:
                raise ValueError("A recorded audit failed independent witness replay")
            audits[compound_id][key] = certificate
            verifications[compound_id][key] = {
                **verification,
                "certificate_sha256": certificate["certificate_sha256"],
                "verification_execution": "recorded_at_export",
            }
    return audits, verifications


def _validate_terms(terms: list[dict]) -> None:
    """Check each feature calculation, including signs and the saved scaling reference."""
    if [term["name"] for term in terms] != FEATURE_NAMES:
        raise ValueError("An assessment does not explain every fitted feature")
    for term in terms:
        if not math.isfinite(term["scale"]) or term["scale"] <= 0:
            raise ValueError("Assessment feature scales must be positive and finite")
        for suffix in ("before", "after"):
            standardized = (term[f"value_{suffix}"] - term["mean"]) / term["scale"]
            contribution = standardized * term["coefficient"]
            if not math.isclose(
                standardized, term[f"standardized_{suffix}"], rel_tol=1e-11, abs_tol=1e-12
            ) or not math.isclose(
                contribution, term[f"contribution_{suffix}"], rel_tol=1e-11, abs_tol=1e-12
            ):
                raise ValueError(
                    "Assessment feature contribution disagrees with the fitted formula"
                )
        if not math.isclose(
            term["contribution_after"] - term["contribution_before"],
            term["contribution_delta"],
            rel_tol=1e-11,
            abs_tol=1e-12,
        ):
            raise ValueError("Assessment feature change disagrees with its before/after terms")


def _validate_assessment(assessment: dict, baseline_evidence: dict, current_evidence: dict) -> None:
    """Reject stale, missing or arithmetically inconsistent selected-pair explanations."""
    decomposition = assessment["decomposition"]
    terms = decomposition["features"]
    _validate_terms(terms)
    for state_name, suffix, evidence in (
        ("baseline", "before", baseline_evidence),
        ("current", "after", current_evidence),
    ):
        state = assessment[state_name]
        if (
            state["features"] != evidence["counts"]
            or state["evidence_count"] != evidence["total_paths"]
        ):
            raise ValueError("Assessment and evidence counts differ")
        if state["supported"] != (state["evidence_count"] > 0):
            raise ValueError("Assessment support status disagrees with the evidence")
        if (state["rank"] is not None) != state["supported"]:
            raise ValueError("An unsupported assessment cannot have a supported rank")
        logit = state["logit"]
        if not math.isfinite(logit) or not math.isfinite(state["score"]):
            raise ValueError("Assessment scores and logits must be finite")
        reconstructed = decomposition["intercept"] + math.fsum(
            term[f"contribution_{suffix}"] for term in terms
        )
        expected_score = (
            1 / (1 + math.exp(-logit)) if logit >= 0 else math.exp(logit) / (1 + math.exp(logit))
        )
        if not math.isclose(reconstructed, logit, rel_tol=1e-11, abs_tol=1e-12):
            raise ValueError("Assessment contributions do not reconstruct the logit")
        if not math.isclose(expected_score, state["score"], rel_tol=1e-11, abs_tol=1e-12):
            raise ValueError("Assessment logit does not reconstruct its score")
    expected_delta = assessment["current"]["logit"] - assessment["baseline"]["logit"]
    if not math.isclose(
        math.fsum(term["contribution_delta"] for term in terms),
        expected_delta,
        rel_tol=1e-11,
        abs_tol=1e-12,
    ) or not math.isclose(
        assessment["delta"]["logit"], expected_delta, rel_tol=1e-11, abs_tol=1e-12
    ):
        raise ValueError("Assessment changes do not reconstruct the logit change")
    if not math.isclose(
        assessment["delta"]["score"],
        assessment["current"]["score"] - assessment["baseline"]["score"],
        rel_tol=1e-11,
        abs_tol=1e-12,
    ):
        raise ValueError("Assessment score change disagrees with its before/after values")


def _validate_ranking(case: dict, key: str, ranking: dict) -> None:
    """Bind every displayed candidate to its exact evidence and score assessment."""
    for candidate in ranking["candidates"]:
        if candidate["id"] not in case["evidence"]:
            raise ValueError("A displayed candidate is missing evidence")
        evidence = case["evidence"][candidate["id"]].get(key)
        if evidence is None:
            raise ValueError("A displayed candidate is missing scenario evidence")
        if evidence["counts"] != candidate["features"]:
            raise ValueError("Displayed path counts do not match ranking features")
        if evidence["total_paths"] != candidate["evidence_count"]:
            raise ValueError("Displayed total evidence count is inconsistent")
        if set(evidence["excluded"]) != set(ranking["excluded"]):
            raise ValueError("Evidence and ranking refer to different configurations")
        if any(edge["type"] in ranking["excluded"] for edge in evidence["edges"]):
            raise ValueError("A removed family appears in a published explanation")
        assessment = case["assessments"][candidate["id"]].get(key)
        if assessment is None:
            raise ValueError("A displayed candidate is missing its scenario assessment")
        current = assessment["current"]
        if current["rank"] != candidate["rank"] or not math.isclose(
            current["score"], candidate["score"], rel_tol=0, abs_tol=5e-9
        ):
            raise ValueError("Assessment and ranking disagree")


def validate_case(case: dict) -> None:
    """Fail export if any displayed ranking, evidence configuration or endpoint is missing."""
    expected = {",".join(excluded) for excluded in exclusion_combinations()}
    if set(case["rankings"]) != expected or set(case["challenges"]) != expected:
        raise ValueError("A published case is missing an evidence configuration")
    if set(case.get("assessments", {})) != set(case["evidence"]):
        raise ValueError("A published candidate is missing its score assessment")
    for key, ranking in case["rankings"].items():
        _validate_ranking(case, key, ranking)
    for compound_id, variants in case["evidence"].items():
        if set(variants) != expected:
            raise ValueError("Selected candidates cannot be inspected in all configurations")
        assessments = case["assessments"][compound_id]
        if set(assessments) != expected:
            raise ValueError("Selected candidates need assessments in all configurations")
        for key, assessment in assessments.items():
            if (
                assessment["compound"]["id"] != compound_id
                or assessment["disease"] != case["disease"]
                or ",".join(assessment["excluded"]) != key
            ):
                raise ValueError("Assessment identity or exclusions do not match the case")
            _validate_assessment(assessment, variants[""], variants[key])
    _validate_audits(case)


def _validate_audits(case: dict) -> None:
    """Bind every recorded verification to the precise selected pair and certificate."""
    audits, verifications = case.get("audits", {}), case.get("audit_verifications", {})
    if set(audits) != set(case["assessments"]) or set(verifications) != set(audits):
        raise ValueError("A published candidate is missing its audit or verification")
    expected = {
        f"{top_k}:{budget}" for top_k, budget in itertools.product(AUDIT_TOP_K, AUDIT_BUDGETS)
    }
    for compound_id, variants in audits.items():
        if set(variants) != expected or set(verifications[compound_id]) != expected:
            raise ValueError("A published candidate is missing an audit configuration")
        for key, certificate in variants.items():
            AuditResponse.model_validate(certificate)
            if (
                certificate["disease"] != case["disease"]
                or certificate["compound"]["id"] != compound_id
                or f"{certificate['top_k']}:{certificate['budget']}" != key
                or certificate_digest(certificate) != certificate["certificate_sha256"]
            ):
                raise ValueError("Audit identity, scope key, or content checksum does not match")
            verification = verifications[compound_id][key]
            if (
                verification.get("valid") is not True
                or verification.get("status") != "verified"
                or verification.get("errors") != []
                or verification.get("certificate_sha256") != certificate["certificate_sha256"]
                or verification.get("verification_execution") != "recorded_at_export"
            ):
                raise ValueError("Recorded verification does not validate this exact certificate")


def _write_snapshot(
    engine: GraphEngine, output: Path, disease_ids=DEFAULT_DISEASES, top_k: int = 12
) -> dict:
    """Write a complete generation in an isolated staging directory."""
    started = time.perf_counter()
    if top_k < 1 or top_k > 100:
        raise ValueError("Snapshot top_k must be between 1 and 100")
    disease_ids = tuple(dict.fromkeys(disease_ids))
    if not disease_ids:
        raise ValueError("At least one disease is required")
    output = Path(output)
    (output / "cases").mkdir(parents=True, exist_ok=True)
    cases, diseases, files = {}, [], []
    auditor = BindingAuditor(engine)
    for disease_id in disease_ids:
        case = build_case(engine, disease_id, top_k, auditor=auditor)
        validate_case(case)
        filename = case_filename(case["disease"])
        path = output / filename
        write_json(path, case)
        content = path.read_bytes()
        cases[disease_id] = {"file": filename, "coverage": case["coverage"]}
        diseases.append(case["disease"])
        files.append(
            {"path": filename, "bytes": len(content), "sha256": hashlib.sha256(content).hexdigest()}
        )
        print(f"Exported {case['disease']['name']}: {len(content):,} bytes", flush=True)
    graph_sha256 = hashlib.sha256((engine.data_dir / "graph.json").read_bytes()).hexdigest()
    manifest = {
        "mode": "snapshot",
        "schema_version": "1.0",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "generated_by": "python -m scripts.export_snapshot",
        "default_disease_id": disease_ids[0],
        "diseases": diseases,
        "compounds": [
            {"id": identifier, "name": engine.nodes[identifier]["name"]}
            for identifier in engine.entities["Compound"]
        ],
        "cases": cases,
        "stats": {**engine.stats(), "graph_sha256": graph_sha256},
        "provenance": engine.provenance(),
        "evaluation": engine.evaluation(),
        "health": {
            "status": "ok",
            "graph_backend": "published research snapshot",
            "agent_mode": "deterministic",
            "dataset_ready": True,
            "version": __version__,
        },
        "dataset_sha256": engine.manifest.get("dataset_sha256"),
        "graph_sha256": graph_sha256,
        "model_sha256": engine.model.get("model_sha256")
        or hashlib.sha256(json.dumps(engine.model, sort_keys=True).encode()).hexdigest(),
        "files": files,
        "file_count": len(files),
        "case_count": len(cases),
        "total_case_bytes": sum(item["bytes"] for item in files),
        "exclusion_configurations_per_case": 16,
        "full_application_disease_count": len(engine.entities["Disease"]),
        "scope": (
            f"Published, recorded results for {len(cases)} research cases. All sixteen family "
            "exclusion configurations are included. The full Docker application queries "
            "Neo4j and can investigate every disease in the dataset."
        ),
        "agent_disclosure": (
            "The hosted snapshot formats retrieved records deterministically. No live LLM "
            "or live database executes in this static edition. The full application exposes "
            "the LangGraph workflow and configured LLM provider."
        ),
        "audit_disclosure": (
            "Global BINDS-withdrawal certificates and their successful verification were "
            "computed at export. The hosted edition retrieves these recorded results; it "
            "does not execute the solver or independently replay graph edits in the browser."
        ),
        "disclaimer": DISCLAIMER,
        "runtime_seconds": round(time.perf_counter() - started, 3),
    }
    write_json(output / "manifest.json", manifest)
    return manifest


def _check_destination(output: Path, data_dir: Path) -> None:
    """Only replace a generated snapshot, never source inputs or unrelated files."""
    if output.is_symlink() or data_dir.resolve().is_relative_to(output.resolve()):
        raise ValueError("Snapshot output must not replace the source data or its ancestors")
    if not output.exists():
        return
    if not output.is_dir():
        raise ValueError("Snapshot output must be a directory")
    if not any(output.iterdir()):
        return
    manifest_path = output / "manifest.json"
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise ValueError(
            "Existing output is not a generated snapshot; use an empty directory"
        ) from error
    if not isinstance(manifest, dict) or manifest.get("mode") != "snapshot":
        raise ValueError("Existing output is not a generated snapshot; use an empty directory")
    recorded = {"manifest.json"} | {
        item["path"]
        for item in manifest.get("files", [])
        if isinstance(item, dict) and isinstance(item.get("path"), str)
    }
    if any(
        path.relative_to(output).as_posix() not in recorded
        for path in output.rglob("*")
        if path.is_file()
    ):
        raise ValueError("Snapshot output contains unrecognized files; use an empty directory")


def export_snapshot(
    engine: GraphEngine, output: Path, disease_ids=DEFAULT_DISEASES, top_k: int = 12
) -> dict:
    """Publish only a complete generation; a failed build preserves the previous bytes."""
    output = Path(output)
    _check_destination(output, engine.data_dir)
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(
        prefix=f".{output.name}-build-", dir=output.parent
    ) as directory:
        stage = Path(directory) / "snapshot"
        manifest = _write_snapshot(engine, stage, disease_ids, top_k)
        previous = Path(directory) / "previous"
        if output.exists():
            output.rename(previous)
        try:
            stage.rename(output)
        except BaseException:
            # Restore the complete prior generation even if publication is interrupted.
            if previous.exists():
                previous.rename(output)
            raise
    return manifest


def main() -> None:
    """Generate the browser's data directory from executed graph/model artifacts."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=Path("data/processed"))
    parser.add_argument("--output", type=Path, default=Path("frontend/data"))
    parser.add_argument("--disease", action="append", help="Disease ID; may be repeated")
    parser.add_argument("--top-k", type=int, default=12)
    args = parser.parse_args()
    manifest = export_snapshot(
        GraphEngine(args.data_dir), args.output, args.disease or DEFAULT_DISEASES, args.top_k
    )
    print(
        json.dumps(
            {
                key: manifest[key]
                for key in ("case_count", "file_count", "total_case_bytes", "runtime_seconds")
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
